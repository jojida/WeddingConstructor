/** Текст шаблона набран заглавными («Флоральный») — варианты тоже заглавными,
    иначе блок выбьется из дизайна. */
export function isUpperCaseText(text?: string): boolean {
  return !!text && /[А-ЯЁA-Z]/.test(text) && text === text.toLocaleUpperCase('ru-RU');
}

/** Варианты для поля: со сроком ответа анкеты по дате свадьбы пары, не длиннее
    лимита поля, заглавными, если так набран текст шаблона. Нет вариантов — []. */
export function textVariantsFor(fieldId: string, opts: { maxLength?: number; weddingDate?: string; upperCase?: boolean } = {}): TextVariant[] {
  const list = TEXT_VARIANTS[fieldId];
  if (!list) return [];
  const deadline = rsvpDeadline(opts.weddingDate);
  return list
    .map(v => {
      const text = v.text.replace(/\{\{rsvpDate\}\}/g, deadline);
      return { tone: v.tone, text: opts.upperCase ? text.toLocaleUpperCase('ru-RU') : text };
    })
    .filter(v => !opts.maxLength || v.text.length <= opts.maxLength);
}
