import TemplatesCatalog from './TemplatesCatalog';

/* Каталог собирается заранее, при выкладке, и первые карточки приходят уже нарисованными.
   Примеры дат свадьбы в превью считаются как «сегодня + N дней». Раньше «сегодня» каждый
   считал сам: сервер — в день сборки, браузер — в день визита, и в любой другой день
   число в превью расходилось. React тогда выбрасывал готовую страницу и рисовал её
   заново (ошибка #418, в Метрике — цель «Ошибка на странице»). Теперь «сегодня»
   берётся один раз здесь, на сервере, и приходит в браузер вместе со страницей.
   Пример может отставать на дни от реального «сегодня + N» — для примера это неважно. */
const SAMPLE_FROM = Date.now();

export default function TemplatesPage() {
  return <TemplatesCatalog sampleFrom={SAMPLE_FROM} />;
}
